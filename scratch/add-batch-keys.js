let content = fs.readFileSync('lib/i18n.ts', 'utf8');
const langs = ['en', 'ta', 'hi', 'ml', 'kn'];

langs.forEach((lang, langIdx) => {
  const marker = `${lang}: {`;
  const idx = content.indexOf(marker);
  if (idx === -1) {
    console.error(`Marker not found for ${lang}`);
    return;
  }
  
  let additions = `\n    // Added batch keys\n`;
  for (const [key, translations] of Object.entries(NEW_KEYS)) {
    // check if key already in this language block
    const blockMatch = content.match(new RegExp(`${lang}:\\s*\\{([\\s\\S]*?)\\n\\s*\\},`));
    if (blockMatch && !new RegExp(`\\b${key}:`).test(blockMatch[1])) {
      const val = translations[langIdx].replace(/"/g, '\\"');
      additions += `    ${key}: "${val}",\n`;
    }
  }

  // Insert additions right after the marker
  content = content.slice(0, idx + marker.length) + additions + content.slice(idx + marker.length);
});

fs.writeFileSync('lib/i18n.ts', content, 'utf8');
console.log('Successfully added batch keys to lib/i18n.ts');
